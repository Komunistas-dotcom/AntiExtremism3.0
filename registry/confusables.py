# Латинские буквы, которые в кириллическом тексте выглядят как кириллические.
# Нужны для обратного случая: латинская 'c' внутри русского названия.
LATIN_TO_CYRILLIC: dict[str, str] = {
    "a": "а",
    "b": "в",
    "c": "с",
    "e": "е",
    "h": "н",
    "k": "к",
    "m": "м",
    "o": "о",
    "p": "р",
    "t": "т",
    "x": "х",
    "y": "у",
    "A": "А",
    "B": "В",
    "C": "С",
    "E": "Е",
    "H": "Н",
    "K": "К",
    "M": "М",
    "O": "О",
    "P": "Р",
    "T": "Т",
    "X": "Х",
    "Y": "У",
}


# Расширенная таблица — только для доменных имён.
#
# Внутри домена кириллица недопустима по стандарту, поэтому здесь можно
# заменять и «похожие, но различимые» буквы: ``vк.соm``, ``оk.ru``.
# В путях и именах аккаунтов такая замена испортила бы настоящие названия,
# поэтому там используется узкая таблица HOMOGLYPHS.
DOMAIN_HOMOGLYPHS: dict[str, str] = dict(HOMOGLYPHS)
DOMAIN_HOMOGLYPHS.update(
    {
        "в": "b",
        "к": "k",
        "м": "m",
        "н": "h",
        "т": "t",
    }
)


def has_homoglyphs(text: str) -> bool:
    """Есть ли в строке буквы, притворяющиеся латиницей."""
    return any(ch in HOMOGLYPHS for ch in text)


def has_non_latin(text: str) -> bool:
    """Есть ли в строке хоть одна нелатинская буква."""
    return any(is_non_latin_letter(ch) for ch in text)


def is_mixed_script(text: str) -> bool:
    """Смешаны ли в строке латиница и нелатинские буквы.

    Именно смешанное написание неоднозначно: непонятно, какой алфавит
    задумывался. Однородная строка сомнений не вызывает.
    """
    has_latin = any(is_ascii_letter(ch) for ch in text)
    return has_latin and has_non_latin(text)


def domain_to_latin(text: str) -> str:
    """Привести доменное имя к латинице по расширенной таблице."""
    return "".join(DOMAIN_HOMOGLYPHS.get(ch, ch) for ch in text)


def to_cyrillic(text: str) -> str:
    """Заменить латинские буквы на неотличимые кириллические.

    Нужно для обратного случая: настоящее кириллическое название, в котором
    составитель реестра набрал часть букв латиницей («НАША» кириллицей,
    «MOBA» латиницей). Правильный вариант здесь — кириллический.
    """
    return "".join(LATIN_TO_CYRILLIC.get(ch, ch) for ch in text)


def cyrillic_variant(text: str) -> str | None:
    """Полностью кириллический вариант строки, если он отличается."""
    converted = to_cyrillic(text)
    return converted if converted != text else None


def is_ascii_letter(ch: str) -> bool:
    return ("a" <= ch <= "z") or ("A" <= ch <= "Z")


def is_non_latin_letter(ch: str) -> bool:
    """Буква вне латиницы (кириллица, греческий и т. п.)."""
    if not ch.isalpha():
        return False
    return not is_ascii_letter(ch)


def to_latin(text: str) -> str:
    """Заменить все омоглифы на латиницу, безусловно."""
    return "".join(HOMOGLYPHS.get(ch, ch) for ch in text)


def fix_segment(segment: str) -> tuple[str, bool]:
    """Исправить один сегмент адреса, если он выглядит как опечатка.

    Возвращает ``(исправленный_текст, было_ли_исправление)``.

    Правило: исправляем только **смешанные** сегменты, где рядом стоят
    латиница и похожие на неё нелатинские буквы. Сегмент, целиком
    состоящий из нелатинских букв, считаем настоящим названием.

    >>> fix_segment("раra2022")          # р, а — кириллические
    ('para2022', True)
    >>> fix_segment("ОбществоГомель")    # настоящее название
    ('ОбществоГомель', False)
    >>> fix_segment("channel")
    ('channel', False)
    """
    if not has_homoglyphs(segment):
        return segment, False

    has_latin = any(is_ascii_letter(ch) for ch in segment)
    # Нелатинские буквы, для которых нет латинского двойника
    # (например 'б', 'ж', 'щ') — верный признак настоящего названия.
    has_genuine_non_latin = any(
        is_non_latin_letter(ch) and ch not in HOMOGLYPHS for ch in segment
    )

    if has_genuine_non_latin:
        # Например "ОбществоГомель": есть 'б', 'щ' — название настоящее.
        return segment, False

    if not has_latin:
        # Сегмент целиком из омоглифов, латиницы нет вообще.
        # Однозначно решить нельзя — оставляем как есть, вызывающий код
        # проиндексирует и латинский вариант отдельно.
        return segment, False

    return to_latin(segment), True


def latin_variant(text: str) -> str | None:
    """Полностью латинский вариант строки, если он отличается от исходной.

    Используется как *дополнительный* ключ в индексе для неоднозначных
    случаев вроде ``t.me/с/123`` (кириллическая 'с' — сегмент целиком
    из омоглифов, поэтому ``fix_segment`` его не трогает).
    """
    converted = to_latin(text)
    return converted if converted != text else None
